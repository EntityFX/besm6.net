namespace Besm6.Architecture
{

    /// <summary>
    /// Опкоды инструкций БЭСМ-6 (восьмеричные номера).
    /// </summary>
    public enum Opcode : ushort
    {
        // 000–037 (короткий формат, арифметика + логика)
        /// <summary>ЗП — запись аккумулятора.</summary>
        Atx = 0x00,
        /// <summary>ЗПМ — запись аккумулятора и извлечение из стека.</summary>
        Stx = 0x01,
        /// <summary>РЕГ — изменение привилегированных регистров.</summary>
        Mod = 0x02,
        /// <summary>СЧМ — укладка аккумулятора в стек и чтение операнда.</summary>
        Xts = 0x03,
        /// <summary>СЛ — сложение.</summary>
        APlusX = 0x04,
        /// <summary>ВЧ — вычитание.</summary>
        AMinusX = 0x05,
        /// <summary>ВЧОБ — обратное вычитание.</summary>
        XMinusA = 0x06,
        /// <summary>ВЧАБ — вычитание модулей.</summary>
        Amx = 0x07,
        /// <summary>СЧ — чтение слова в аккумулятор.</summary>
        Xta = 0x08,
        /// <summary>И — логическое И.</summary>
        Aax = 0x09,
        /// <summary>НТЖ — неравнозначность.</summary>
        Aex = 0x0A,
        /// <summary>СЛЦ — циклическое сложение.</summary>
        Arx = 0x0B,
        /// <summary>ЗНАК — изменение знака.</summary>
        Avx = 0x0C,
        /// <summary>ИЛИ — логическое ИЛИ.</summary>
        Aox = 0x0D,
        /// <summary>ДЕЛ — деление.</summary>
        ADivX = 0x0E,
        /// <summary>УМН — умножение.</summary>
        AMulX = 0x0F,
        /// <summary>СБР — сборка разрядов.</summary>
        Apx = 0x10,
        /// <summary>РЗБ — разборка разрядов.</summary>
        Aux = 0x11,
        /// <summary>ЧЕД — число единиц.</summary>
        Acx = 0x12,
        /// <summary>НЕД — номер единицы.</summary>
        Anx = 0x13,
        /// <summary>СЛП — сложение порядков.</summary>
        EPlusX = 0x14,
        /// <summary>ВЧП — вычитание порядков.</summary>
        EMinusX = 0x15,
        /// <summary>СД — сдвиг по порядку операнда.</summary>
        Asx = 0x16,
        /// <summary>РЖ — установка регистра режима.</summary>
        Xtr = 0x17,
        /// <summary>СЧРЖ — чтение регистра режима.</summary>
        Rte = 0x18,
        /// <summary>СЧМР — чтение регистра младших разрядов.</summary>
        Yta = 0x19,
        /// <summary>ЗПП — полноразрядная запись во внешнее устройство.</summary>
        Ext = 0x1A,
        /// <summary>СЧП — полноразрядное чтение из внешнего устройства.</summary>
        Op33 = 0x1B,
        /// <summary>СЛПА — сложение порядка с адресом.</summary>
        EPlusN = 0x1C,
        /// <summary>ВЧПА — вычитание порядка из адреса.</summary>
        EMinusN = 0x1D,
        /// <summary>СДА — сдвиг по адресу.</summary>
        Asn = 0x1E,
        /// <summary>РЖА — установка регистра режима из адреса.</summary>
        Ntr = 0x1F,

        // 040–047 (индекс-регистры)
        /// <summary>УИ — пересылка аккумулятора в индексный регистр.</summary>
        Ati = 0x20,
        /// <summary>УИМ — запись в индексный регистр и извлечение из стека.</summary>
        Sti = 0x21,
        /// <summary>СЧИ — чтение индексного регистра в аккумулятор.</summary>
        Ita = 0x22,
        /// <summary>СЧИМ — укладка аккумулятора в стек и чтение индексного регистра.</summary>
        Its = 0x23,
        /// <summary>УИИ — пересылка индексного регистра.</summary>
        Mtj = 0x24,
        /// <summary>СЛИ — сложение индексных регистров.</summary>
        JPlusM = 0x25,
        /// <summary>СОП — специальное обращение к памяти.</summary>
        Op46 = 0x26,
        /// <summary>Э47 — зарезервированная инструкция.</summary>
        Op47 = 0x27,

        // 0220–0230 (модификатор, длинный формат)
        /// <summary>МОДА — установка регистра модификации адресом.</summary>
        Utc = 0x90,
        /// <summary>МОД — установка регистра модификации из памяти.</summary>
        Wtc = 0x98,

        // 0240–0250 (индекс, длинный формат)
        /// <summary>УИА — установка индексного регистра адресом.</summary>
        Vtm = 0xA0,
        /// <summary>СЛИА — сложение индексного регистра с адресом.</summary>
        Utm = 0xA8,

        // 0260–0270 (условные переходы)
        /// <summary>ПО — переход по нулю.</summary>
        Uza = 0xB0,
        /// <summary>ПЕ — переход по единице.</summary>
        U1a = 0xB8,

        // 0300–0310 (неусловные переходы)
        /// <summary>ПБ — безусловный переход.</summary>
        Uj = 0xC0,
        /// <summary>ПВ — переход с возвратом.</summary>
        Vjm = 0xC8,

        // 0320–0330 (служебные)
        /// <summary>ВЫПР — возврат из прерывания.</summary>
        Ij = 0xD0,
        /// <summary>СТОП — останов процессора.</summary>
        Stop = 0xD8,

        // 0340–0350 (условные по M[reg])
        /// <summary>ПИО — переход, если индексный регистр равен нулю.</summary>
        Vzm = 0xE0,
        /// <summary>ПИНО — переход, если индексный регистр не равен нулю.</summary>
        V1m = 0xE8,

        // 0360–0370 (цикл)
        /// <summary>Э36 — недокументированный вариант ПИО.</summary>
        Op36 = 0xF0,
        /// <summary>ЦИКЛ — организация цикла по индексному регистру.</summary>
        Vlm = 0xF8,
    }
}
