namespace Besm6.EduCpu;

/// <summary>Учебные коды операций процессора (значения — восьмеричные коды).</summary>
public enum Op : ushort
{
    Atx = 0,    // 000 — ЗП: mem[адрес] = ACC
    Sub = 1,    // 001 — ВЫЧ: ACC = ACC - mem[адрес] (по модулю 2^48)
    Mul = 2,    // 002 — УМН: ACC = (ACC * mem[адрес]), младшие 24 бита операндов
    Xta = 8,    // 010 — СЧ: ACC = mem[адрес]
    Aax = 9,    // 011 — И: ACC &= mem[адрес]
    Aex = 10,   // 012 — НТЖ: ACC ^= mem[адрес]
    Arx = 11,   // 013 — СЛЦ: циклическое сложение ACC и слова памяти
    Aox = 13,   // 015 — ИЛИ: ACC |= mem[адрес]
    Vtm = 160,  // 0240 — УИА: M[регистр] = поле адреса
    Uza = 176,  // 0260 — ПО: переход, если ACC == 0
    Uj = 192,   // 0300 — ПБ: безусловный переход
    Stop = 216, // 0330 — СТОП: останов процессора
}