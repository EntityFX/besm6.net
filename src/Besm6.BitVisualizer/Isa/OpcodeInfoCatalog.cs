using Besm6.Architecture;

namespace Besm6.BitVisualizer;

internal static class OpcodeInfoCatalog
{
    public static (string Mnemonic, string Description) Get(Opcode opcode, InstructionFormat format)
    {
        (string, string)? known = opcode switch
        {
            Opcode.Atx => ("ЗП", "запись аккумулятора в память"),
            Opcode.Stx => ("ЗПМ", "запись аккумулятора и извлечение из стека"),
            Opcode.Mod => ("РЕГ", "изменение привилегированных регистров"),
            Opcode.Xts => ("СЧМ", "укладка аккумулятора в стек и чтение операнда"),
            Opcode.APlusX => ("СЛ", "сложение аккумулятора с операндом"),
            Opcode.AMinusX => ("ВЧ", "вычитание операнда из аккумулятора"),
            Opcode.XMinusA => ("ВЧОБ", "обратное вычитание"),
            Opcode.Amx => ("ВЧАБ", "вычитание модулей"),
            Opcode.Xta => ("СЧ", "чтение слова в аккумулятор"),
            Opcode.Aax => ("И", "логическое И"),
            Opcode.Aex => ("НТЖ", "логическая неравнозначность"),
            Opcode.Arx => ("СЛЦ", "циклическое сложение"),
            Opcode.Avx => ("ЗНАК", "изменение знака"),
            Opcode.Aox => ("ИЛИ", "логическое ИЛИ"),
            Opcode.ADivX => ("ДЕЛ", "деление"),
            Opcode.AMulX => ("УМН", "умножение"),
            Opcode.Apx => ("СБР", "сборка разрядов"),
            Opcode.Aux => ("РЗБ", "разборка разрядов"),
            Opcode.Acx => ("ЧЕД", "подсчёт числа единиц"),
            Opcode.Anx => ("НЕД", "поиск номера единицы"),
            Opcode.EPlusX => ("СЛП", "сложение порядков"),
            Opcode.EMinusX => ("ВЧП", "вычитание порядков"),
            Opcode.Asx => ("СД", "сдвиг по порядку операнда"),
            Opcode.Xtr => ("РЖ", "установка регистра режима"),
            Opcode.Rte => ("СЧРЖ", "чтение регистра режима"),
            Opcode.Yta => ("СЧМР", "чтение регистра младших разрядов"),
            Opcode.Ext => ("ЗПП", "полноразрядная запись во внешнее устройство"),
            Opcode.Op33 => ("СЧП", "полноразрядное чтение из внешнего устройства"),
            Opcode.EPlusN => ("СЛПА", "сложение порядка с адресом"),
            Opcode.EMinusN => ("ВЧПА", "вычитание порядка из адреса"),
            Opcode.Asn => ("СДА", "сдвиг по адресу"),
            Opcode.Ntr => ("РЖА", "установка регистра режима из адреса"),
            Opcode.Ati => ("УИ", "пересылка аккумулятора в индексный регистр"),
            Opcode.Sti => ("УИМ", "запись в индексный регистр и извлечение из стека"),
            Opcode.Ita => ("СЧИ", "чтение индексного регистра в аккумулятор"),
            Opcode.Its => ("СЧИМ", "укладка аккумулятора в стек и чтение индексного регистра"),
            Opcode.Mtj => ("УИИ", "пересылка индексного регистра"),
            Opcode.JPlusM => ("СЛИ", "сложение индексных регистров"),
            Opcode.Op46 => ("СОП", "специальное обращение к памяти"),
            Opcode.Op47 => ("Э47", "зарезервированная операция"),
            Opcode.Utc => ("МОДА", "установка регистра модификации адресом"),
            Opcode.Wtc => ("МОД", "установка регистра модификации из памяти"),
            Opcode.Vtm => ("УИА", "установка индексного регистра адресом"),
            Opcode.Utm => ("СЛИА", "сложение индексного регистра с адресом"),
            Opcode.Uza => ("ПО", "переход по нулю"),
            Opcode.U1a => ("ПЕ", "переход по единице"),
            Opcode.Uj => ("ПБ", "безусловный переход"),
            Opcode.Vjm => ("ПВ", "переход с возвратом"),
            Opcode.Ij => ("ВЫПР", "возврат из прерывания"),
            Opcode.Stop => ("СТОП", "останов процессора"),
            Opcode.Vzm => ("ПИО", "переход, если индексный регистр равен нулю"),
            Opcode.V1m => ("ПИНО", "переход, если индексный регистр не равен нулю"),
            Opcode.Op36 => ("Э36", "недокументированный вариант перехода"),
            Opcode.Vlm => ("ЦИКЛ", "организация цикла по индексному регистру"),
            _ => null,
        };

        if (known.HasValue)
            return known.Value;

        string code = Convert.ToString((int)opcode, 8).PadLeft(format == InstructionFormat.Short ? 2 : 3, '0');
        return format == InstructionFormat.Short && (int)opcode is >= 0x28 and <= 0x3F
            ? ($"Э{code}", "Экстракод БЭСМ-6")
            : ($"*{code}", "Неименованная операция БЭСМ-6");
    }
}
